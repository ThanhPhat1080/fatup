export const dictionaries = { en, vi } as const;
export type Locale = keyof typeof dictionaries;

export function resolveLocale(pref: Lang, systemLocale: string): Locale {
  if (pref !== 'auto') return pref;
  return systemLocale.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

export function errorText(t: Dict, code: string): string {
  const key = `err_${code}` as keyof Dict;
  const value = t[key];
  return typeof value === 'string' ? value : t.err_generic;
}

export const I18nContext = createContext<{ t: Dict; locale: Locale }>({ t: en, locale: 'en' });
export const useI18n = () => useContext(I18nContext);
